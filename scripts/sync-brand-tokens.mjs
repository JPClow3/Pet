import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(
  await readFile(path.join(root, "assets/design-tokens.json"), "utf8"),
);
const declarations = (palette) =>
  Object.entries(palette)
    .map(([name, value]) => `  --color-${name}: ${value};`)
    .join("\n");
const css = `/* Generated by pnpm brand:sync. Edit assets/design-tokens.json. */
@theme {
${declarations(tokens.light)}
}

.dark {
${declarations(tokens.dark)}
}
`;
const { mark, light, brand } = tokens;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${mark.viewBox}" fill="none"><title>${brand.name}</title><rect width="64" height="64" rx="20" fill="${light.brand}"/><path d="${mark.path}" stroke="${light.canvas}" stroke-width="${mark.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"/><circle cx="${mark.dot.cx}" cy="${mark.dot.cy}" r="${mark.dot.r}" fill="${light.accent}"/></svg>\n`;
const outputs = {
  "assets/design-tokens.css": css,
  "public/brand/zelupi-symbol.svg": svg,
  "src/app/icon.svg": svg,
};
for (const [relative, content] of Object.entries(outputs)) {
  const target = path.join(root, relative);
  if (process.argv.includes("--check")) {
    const existing = await readFile(target, "utf8").catch(() => "");
    if (existing !== content)
      throw new Error(`Brand asset is stale: ${relative}`);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log(`updated ${relative}`);
  }
}
